/* The game a title is part of: updates are <game> | 0x800, DLC
 * <game> + 0x1000 + n. */
static uint64_t swa_base_of(uint64_t t)
{
   if ((t & 0xFFF) == 0x800)
      return t & ~0xFFFULL;
   if ((t & 0xFFF) == 0)
      return t;
   return (t - 0x1000) & ~0xFFFULL;
}

static uint64_t swa_le64(const uint8_t *p)
{
   uint64_t v = 0;
   int i;
   for (i = 7; i >= 0; i--)
      v = (v << 8) | p[i];
   return v;
}

static uint32_t swa_le32(const uint8_t *p)
{
   return (uint32_t)p[0] | ((uint32_t)p[1] << 8)
      | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
}

static int swa_hex(char c)
{
   if (c >= '0' && c <= '9')
      return c - '0';
   c = (char)tolower((unsigned char)c);
   if (c >= 'a' && c <= 'f')
      return c - 'a' + 10;
   return -1;
}

static bool swa_is_tid(const char *s)
{
   size_t i;
   for (i = 0; i < 16; i++)
      if (swa_hex(s[i]) < 0)
         return false;
   return s[16] == '\0';
}

/* ---- Reading files ---------------------------------------------------- */

static bool swa_read_at(RFILE *f, int64_t off, void *buf, int64_t len)
{
   return filestream_seek(f, off, RETRO_VFS_SEEK_POSITION_START) == 0
      && filestream_read(f, buf, len) == len;
}

typedef struct
{
   char name[128];
   uint64_t off;    /* in the file */
   uint64_t size;
} swa_entry_t;

/* A PFS0 (entry 0x18 bytes) or HFS0 (0x40) at base: its files, offsets
 * made absolute. Returns how many, -1 if it isn't one. */
static int swa_read_fs(RFILE *f, int64_t base, bool hfs, swa_entry_t *out,
      int max)
{
   uint8_t hdr[16], *tab;
   uint32_t n, strsz, esz = hfs ? 0x40 : 0x18, i;
   int64_t data;
   size_t tlen;

   if (     !swa_read_at(f, base, hdr, 16)
         || memcmp(hdr, hfs ? "HFS0" : "PFS0", 4))
      return -1;
   n     = swa_le32(hdr + 4);
   strsz = swa_le32(hdr + 8);
   if (n == 0 || n > (uint32_t)max || strsz > 0x100000)
      return -1;
   tlen = (size_t)n * esz + strsz;
   if (!(tab = (uint8_t*)malloc(tlen + 1)))
      return -1;
   if (!swa_read_at(f, base + 16, tab, (int64_t)tlen))
   {
      free(tab);
      return -1;
   }
   tab[tlen] = 0;
   data = base + 16 + (int64_t)tlen;
   for (i = 0; i < n; i++)
   {
      const uint8_t *e = tab + (size_t)i * esz;
      uint32_t name    = swa_le32(e + 16);
      out[i].off  = (uint64_t)data + swa_le64(e);
      out[i].size = swa_le64(e + 8);
      strlcpy(out[i].name, name < strsz
            ? (const char*)tab + (size_t)n * esz + name : "",
            sizeof(out[i].name));
   }
   free(tab);
   return (int)n;
}

/* The NCAs of an .nsp or .xci (its secure partition). */
static int swa_list_ncas(RFILE *f, const char *path, swa_entry_t *out, int max)
{
   swa_entry_t root[8];
   uint8_t hdr[0x140];
   int i, n;
   int64_t base;

   if (!string_is_equal_noncase(path_get_extension(path), "xci"))
      return swa_read_fs(f, 0, false, out, max);

   /* Card image: "HEAD" at 0x100 (0x1100 with the key area in front),
    * the root HFS0's offset at 0x130. */
   for (base = 0; base <= 0x1000; base += 0x1000)
      if (     swa_read_at(f, base, hdr, sizeof(hdr))
            && !memcmp(hdr + 0x100, "HEAD", 4))
         break;
   if (base > 0x1000)
      return -1;
   n = swa_read_fs(f, base + (int64_t)swa_le64(hdr + 0x130), true, root, 8);
   for (i = 0; i < n; i++)
      if (string_is_equal(root[i].name, "secure"))
         return swa_read_fs(f, (int64_t)root[i].off, true, out, max);
   return -1;
}

/* ---- NCA headers ------------------------------------------------------ */

typedef struct
{
   uint64_t tid;
   uint8_t type;    /* 0 program, 1 meta, 2 control... */
} swa_nca_t;

static bool swa_header_key(const char *user, uint8_t key[32])
{
   char path[PATH_MAX_LENGTH];
   void *buf  = NULL;
   int64_t n  = 0;
   bool ok    = false;
   const char *p;

   fill_pathname_join_special(path, user, "keys/prod.keys", sizeof(path));
   if (!filestream_read_file(path, &buf, &n) || !buf)
      return false;
   for (p = (const char*)buf; (p = strstr(p, "header_key")); p++)
   {
      int i;
      /* At a line's start, "header_key" and nothing more before '='. */
      if (p != (const char*)buf && p[-1] != '\n')
         continue;
      p += 10;
      while (*p == ' ' || *p == '\t')
         p++;
      if (*p++ != '=')
         continue;
      while (*p == ' ' || *p == '\t')
         p++;
      for (i = 0; i < 32; i++)
      {
         int hi = swa_hex(p[2 * i]), lo = hi < 0 ? -1 : swa_hex(p[2 * i + 1]);
         if (lo < 0)
            break;
         key[i] = (uint8_t)(hi << 4 | lo);
      }
      ok = i == 32;
      break;
   }
   free(buf);
   return ok;
}

#ifdef BOMBA_HAVE_AES
/* Nintendo's AES-XTS: data key, tweak key; tweak = sector, big-endian. */
static void swa_xts_decrypt(const uint8_t key[32], uint8_t *data, size_t len,
      uint64_t sector)
{
   mbedtls_aes_context dk, tk;
   size_t s, b;

   mbedtls_aes_init(&dk);
   mbedtls_aes_init(&tk);
   mbedtls_aes_setkey_dec(&dk, key, 128);
   mbedtls_aes_setkey_enc(&tk, key + 16, 128);
   for (s = 0; s < len / 0x200; s++, sector++)
   {
      uint8_t t[16];
      uint64_t v = sector;
      int i;
      for (i = 15; i >= 0; i--)
      {
         t[i] = (uint8_t)(v & 0xFF);
         v  >>= 8;
      }
      mbedtls_aes_crypt_ecb(&tk, MBEDTLS_AES_ENCRYPT, t, t);
      for (b = 0; b < 0x200; b += 16)
      {
         uint8_t *p = data + s * 0x200 + b;
         uint8_t carry;
         for (i = 0; i < 16; i++)
            p[i] ^= t[i];
         mbedtls_aes_crypt_ecb(&dk, MBEDTLS_AES_DECRYPT, p, p);
         for (i = 0; i < 16; i++)
            p[i] ^= t[i];
         /* Next block's tweak: times x in GF(2^128). */
         carry = t[15] >> 7;
         for (i = 15; i > 0; i--)
            t[i] = (uint8_t)(t[i] << 1 | t[i - 1] >> 7);
         t[0] = (uint8_t)(t[0] << 1);
         if (carry)
            t[0] ^= 0x87;
      }
   }
   mbedtls_aes_free(&dk);
   mbedtls_aes_free(&tk);
}
#endif

static bool swa_nca_info(RFILE *f, int64_t off, const uint8_t key[32],
      swa_nca_t *out)
{
#ifdef BOMBA_HAVE_AES
   uint8_t h[0x400];
   if (!swa_read_at(f, off, h, sizeof(h)))
      return false;
   swa_xts_decrypt(key, h, sizeof(h), 0);
   if (memcmp(h + 0x200, "NCA3", 4) && memcmp(h + 0x200, "NCA2", 4))
      return false;
   out->type = h[0x205];
   out->tid  = swa_le64(h + 0x210);
   return true;
#else
   return false;
#endif
}

static bool swa_nca_file_info(const char *path, const uint8_t key[32],
      swa_nca_t *out)
{
   RFILE *f = filestream_open(path, RETRO_VFS_FILE_ACCESS_READ,
         RETRO_VFS_FILE_ACCESS_HINT_NONE);
   bool ok  = f && swa_nca_info(f, 0, key, out);
   if (f)
      filestream_close(f);
   return ok;
}

/* The game's title ID: its program NCA's. */
static bool swa_game_tid(const char *rom, const char *user, uint64_t *tid,
      char *why, size_t why_len)
{
   swa_entry_t *e;
   uint8_t key[32];
   RFILE *f;
   int i, n;
   uint64_t any = 0;

   if (!swa_header_key(user, key))
   {
      strlcpy(why, "Install your Switch keys first (Downloads)", why_len);
      return false;
   }
   if (!(e = (swa_entry_t*)malloc(SWA_MAX_FILES * sizeof(*e))))
      return false;
   if (!(f = filestream_open(rom, RETRO_VFS_FILE_ACCESS_READ,
               RETRO_VFS_FILE_ACCESS_HINT_NONE)))
   {
      free(e);
      strlcpy(why, "Couldn't open the game's file", why_len);
      return false;
   }
   n = swa_list_ncas(f, rom, e, SWA_MAX_FILES);
   for (i = 0; i < n; i++)
   {
      swa_nca_t nca;
      if (     !string_is_equal_noncase(path_get_extension(e[i].name), "nca")
            || !swa_nca_info(f, (int64_t)e[i].off, key, &nca))
         continue;
      if (nca.type == 0 && (nca.tid & 0xFFF) == 0)
      {
         any = nca.tid;
         break;
      }
      if (!any)
         any = swa_base_of(nca.tid);
   }
   filestream_close(f);
   free(e);
   if (!any)
   {
      strlcpy(why, "Couldn't read the game's file (an .nsp or .xci)",
            why_len);
      return false;
   }
   *tid = any;
   return true;
}

/* ---- Manifest (installed updates) ------------------------------------- */

static char *swa_manifest_read(const char *user)
{
   char path[PATH_MAX_LENGTH];
   void *buf = NULL;
   int64_t n = 0;
   fill_pathname_join_special(path, user, SWA_MANIFEST, sizeof(path));
   if (!filestream_read_file(path, &buf, &n))
      return NULL;
   return (char*)buf; /* NUL-terminated by filestream_read_file */
}

static void swa_manifest_write(const char *user, const char *text)
{
   char path[PATH_MAX_LENGTH];
   fill_pathname_join_special(path, user, SWA_MANIFEST, sizeof(path));
   filestream_write_file(path, text, (int64_t)strlen(text));
}

/* The manifest's line for title tid (its label and files, each cut to
 * their buffers). */
static bool swa_manifest_find(const char *text, uint64_t tid, char *label,
      size_t label_len, char *files, size_t files_len)
{
   char id[20];
   const char *line;

   if (!text)
      return false;
   snprintf(id, sizeof(id), "%016llX\t", (unsigned long long)tid);
   for (line = text; line && *line; line = strchr(line, '\n'), line = line ? line + 1 : NULL)
   {
      const char *tab, *end;
      if (strncmp(line, id, 17))
         continue;
      tab = strchr(line + 17, '\t');
      end = strchr(line, '\n');
      if (!end)
         end = line + strlen(line);
      if (!tab || tab > end)
         return false;
      if (label)
         strlcpy(label, line + 17, (size_t)(tab - line - 17) + 1 < label_len
               ? (size_t)(tab - line - 17) + 1 : label_len);
      if (files)
         strlcpy(files, tab + 1, (size_t)(end - tab) < files_len
               ? (size_t)(end - tab) : files_len);
      return true;
   }
   return false;
}

/* The manifest without title tid's line, plus line (unless NULL). */
static void swa_manifest_set(const char *user, uint64_t tid, const char *line)
{
   char id[20];
   char *text = swa_manifest_read(user);
   size_t len = (text ? strlen(text) : 0) + (line ? strlen(line) : 0) + 2;
   char *out  = (char*)malloc(len);
   const char *p;
   size_t o   = 0;

   if (!out)
   {
      free(text);
      return;
   }
   snprintf(id, sizeof(id), "%016llX\t", (unsigned long long)tid);
   for (p = text; p && *p; )
   {
      const char *end = strchr(p, '\n');
      size_t n        = end ? (size_t)(end - p) + 1 : strlen(p);
      if (strncmp(p, id, 17))
      {
         memcpy(out + o, p, n);
         o += n;
         if (!end)
            out[o++] = '\n';
      }
      p += n;
   }
   if (line)
   {
      memcpy(out + o, line, strlen(line));
      o += strlen(line);
   }
   out[o] = '\0';
   swa_manifest_write(user, out);
   free(out);
   free(text);
}

/* ---- Updates and DLC -------------------------------------------------- */

/* Every meta NCA in the NAND that belongs to game (tid), as paths relative
 * to registered, with their title IDs. Returns how many. */
static size_t swa_find_metas(const char *user, uint64_t game, bool exact,
      char rel[][64], uint64_t *tids, size_t max)
{
   char reg[PATH_MAX_LENGTH];
   struct string_list *list;
   uint8_t key[32];
   size_t i, n = 0, rl;

   swa_registered(user, reg, sizeof(reg));
   if (!swa_header_key(user, key) || !path_is_directory(reg))
      return 0;
   if (!(list = dir_list_new(reg, "nca", false, true, false, true)))
      return 0;
   rl = strlen(reg);
   for (i = 0; i < list->size && n < max; i++)
   {
      const char *p = list->elems[i].data;
      swa_nca_t nca;
      if (     list->elems[i].attr.i != RARCH_PLAIN_FILE
            || !swa_nca_file_info(p, key, &nca) || nca.type != 1)
         continue;
      if (exact ? nca.tid != game
                : (swa_base_of(nca.tid) != game || nca.tid == game))
         continue;
      strlcpy(rel[n], p + rl + (p[rl] == '/' || p[rl] == '\\'), 64);
      tids[n++] = nca.tid;
   }
   string_list_free(list);
   return n;
}

/* Removes title tid from the NAND: its files if we installed it, else the
 * meta NCA at rel (NULL: every meta NCA of it). */
static bool swa_remove_title(const char *user, uint64_t tid, const char *rel)
{
   char reg[PATH_MAX_LENGTH], path[PATH_MAX_LENGTH], files[4096];
   char *text = swa_manifest_read(user);
   bool ok    = true;

   swa_registered(user, reg, sizeof(reg));
   if (swa_manifest_find(text, tid, NULL, 0, files, sizeof(files)))
   {
      char *save = NULL, *f;
      for (f = strtok_r(files, "|", &save); f; f = strtok_r(NULL, "|", &save))
      {
         fill_pathname_join_special(path, reg, f, sizeof(path));
         if (path_is_valid(path) && filestream_delete(path) != 0)
            ok = false;
      }
      swa_manifest_set(user, tid, NULL);
   }
   free(text);

   if (rel)
   {
      fill_pathname_join_special(path, reg, rel, sizeof(path));
      if (path_is_valid(path) && filestream_delete(path) != 0)
         ok = false;
   }
   else
   {
      char metas[16][64];
      uint64_t tids[16];
      size_t i, n = swa_find_metas(user, tid, true, metas, tids, 16);
      for (i = 0; i < n; i++)
      {
         fill_pathname_join_special(path, reg, metas[i], sizeof(path));
         if (filestream_delete(path) != 0)
            ok = false;
      }
   }
   return ok;
}

/* A common ticket's title key into title.keys_autogenerated, if new. */
static void swa_add_ticket(const char *user, const uint8_t *tik, size_t len)
{
   static const struct { uint32_t type; uint32_t skip; } sigs[] = {
      { 0x10000, 0x200 + 0x3C }, { 0x10001, 0x100 + 0x3C },
      { 0x10002, 0x3C + 0x40 },  { 0x10003, 0x200 + 0x3C },
      { 0x10004, 0x100 + 0x3C }, { 0x10005, 0x3C + 0x40 },
   };
   char path[PATH_MAX_LENGTH], rights[33], key[33], line[80];
   uint32_t type, skip = 0;
   const uint8_t *d;
   size_t i;
   RFILE *f;

   if (len < 4)
      return;
   type = swa_le32(tik);
   for (i = 0; i < sizeof(sigs) / sizeof(sigs[0]); i++)
      if (sigs[i].type == type)
         skip = 4 + sigs[i].skip;
   if (!skip || len < skip + 0x170)
      return;
   d = tik + skip;
   if (d[0x141] != 0)   /* personalized: tied to the console it came from */
      return;
   for (i = 0; i < 16; i++)
   {
      snprintf(rights + 2 * i, 3, "%02x", d[0x160 + i]);
      snprintf(key + 2 * i, 3, "%02x", d[0x40 + i]);
   }

   fill_pathname_join_special(path, user, "keys/title.keys_autogenerated",
         sizeof(path));
   {
      void *buf = NULL;
      int64_t n = 0;
      bool have = false;
      if (filestream_read_file(path, &buf, &n) && buf)
      {
         char *p;
         for (p = (char*)buf; *p; p++)
            *p = (char)tolower((unsigned char)*p);
         have = strstr((char*)buf, rights) != NULL;
      }
      free(buf);
      if (have)
         return;
   }
   if (!(f = filestream_open(path, RETRO_VFS_FILE_ACCESS_READ_WRITE
               | RETRO_VFS_FILE_ACCESS_UPDATE_EXISTING,
               RETRO_VFS_FILE_ACCESS_HINT_NONE)))
      f = filestream_open(path, RETRO_VFS_FILE_ACCESS_WRITE,
            RETRO_VFS_FILE_ACCESS_HINT_NONE);
   if (!f)
      return;
   filestream_seek(f, 0, RETRO_VFS_SEEK_POSITION_END);
   snprintf(line, sizeof(line), "\n%s = %s", rights, key);
   filestream_write(f, line, (int64_t)strlen(line));
   filestream_close(f);
}

static void swa_install_nsp(swa_job_t *job)
{
   char reg[PATH_MAX_LENGTH], dst[PATH_MAX_LENGTH];
   char *files = NULL, *line = NULL;
   swa_entry_t *e = NULL;
   uint8_t key[32];
   uint64_t tid = 0, total = 0, done = 0;
   size_t flen  = 0, fcap = 8192;
   RFILE *f;
   int i, n;
   uint8_t *chunk = NULL;

   if (!swa_header_key(job->user, key))
   {
      strlcpy(job->error, "Install your Switch keys first", sizeof(job->error));
      return;
   }
   if (!(f = filestream_open(job->src, RETRO_VFS_FILE_ACCESS_READ,
               RETRO_VFS_FILE_ACCESS_HINT_NONE)))
   {
      strlcpy(job->error, "Couldn't open that file", sizeof(job->error));
      return;
   }
   if (     !(e = (swa_entry_t*)malloc(SWA_MAX_FILES * sizeof(*e)))
         || !(files = (char*)malloc(fcap))
         || !(chunk = (uint8_t*)malloc(1 << 20)))
      goto end;
   files[0] = '\0';

   if ((n = swa_read_fs(f, 0, false, e, SWA_MAX_FILES)) <= 0)
   {
      strlcpy(job->error, "That isn't an .nsp", sizeof(job->error));
      goto end;
   }

   /* Which title it is: its meta NCA's. */
   for (i = 0; i < n; i++)
   {
      swa_nca_t nca;
      if (     string_is_equal_noncase(path_get_extension(e[i].name), "nca")
            && swa_nca_info(f, (int64_t)e[i].off, key, &nca)
            && nca.type == 1)
         tid = nca.tid;
      total += e[i].size;
   }
   if (!tid)
   {
      strlcpy(job->error, "Couldn't read that .nsp (check your keys)",
            sizeof(job->error));
      goto end;
   }
   if (tid == job->tid)
   {
      strlcpy(job->error, "That's the game itself, not an update or DLC",
            sizeof(job->error));
      goto end;
   }
   if (swa_base_of(tid) != job->tid)
   {
      strlcpy(job->error, "That's for another game", sizeof(job->error));
      goto end;
   }

   /* Replaces what it had of that title (an older update). */
   swa_remove_title(job->user, tid, NULL);

   swa_registered(job->user, reg, sizeof(reg));
   path_mkdir(reg);
   for (i = 0; i < n; i++)
   {
      const char *ext = path_get_extension(e[i].name);
      size_t nl       = strlen(e[i].name);

      if (string_is_equal_noncase(ext, "tik"))
      {
         uint8_t tik[0x400];
         size_t tl = e[i].size < sizeof(tik) ? (size_t)e[i].size : sizeof(tik);
         if (swa_read_at(f, (int64_t)e[i].off, tik, (int64_t)tl))
            swa_add_ticket(job->user, tik, tl);
         done += e[i].size;
         continue;
      }
      if (!string_is_equal_noncase(ext, "nca") || strchr(e[i].name, '/'))
      {
         done += e[i].size;
         continue;
      }

      /* Copied under its own name: <NCA id>.nca / .cnmt.nca. */
      fill_pathname_join_special(dst, reg, e[i].name, sizeof(dst));
      {
         RFILE *out = filestream_open(dst, RETRO_VFS_FILE_ACCESS_WRITE,
               RETRO_VFS_FILE_ACCESS_HINT_NONE);
         uint64_t left = e[i].size;
         bool ok       = out && filestream_seek(f, (int64_t)e[i].off,
               RETRO_VFS_SEEK_POSITION_START) == 0;
         while (ok && left)
         {
            int64_t want = left < (1 << 20) ? (int64_t)left : (1 << 20);
            ok    = filestream_read(f, chunk, want) == want
                 && filestream_write(out, chunk, want) == want;
            left -= (uint64_t)want;
            done += (uint64_t)want;
            if (total)
               job->progress = (unsigned)(done * 100 / total);
         }
         if (out)
            filestream_close(out);
         if (!ok)
         {
            filestream_delete(dst);
            strlcpy(job->error, "Couldn't copy it (is the drive full?)",
                  sizeof(job->error));
            /* What was copied so far goes too. */
            if (flen)
            {
               char *save = NULL, *p;
               for (p = strtok_r(files, "|", &save); p;
                     p = strtok_r(NULL, "|", &save))
               {
                  fill_pathname_join_special(dst, reg, p, sizeof(dst));
                  filestream_delete(dst);
               }
            }
            goto end;
         }
      }

      if (flen + nl + 2 > fcap)
      {
         char *grown = (char*)realloc(files, fcap * 2 + nl);
         if (!grown)
            goto end;
         files = grown;
         fcap  = fcap * 2 + nl;
      }
      if (flen)
         files[flen++] = '|';
      memcpy(files + flen, e[i].name, nl + 1);
      flen += nl;
   }

   if ((line = (char*)malloc(flen + sizeof(job->label) + 32)))
   {
      snprintf(line, flen + sizeof(job->label) + 32, "%016llX\t%s\t%s\n",
            (unsigned long long)tid, job->label, files);
      swa_manifest_set(job->user, tid, line);
   }
   job->ok = true;

end:
   filestream_close(f);
   free(e);
   free(files);
   free(line);
   free(chunk);
}

/* ---- Mods ------------------------------------------------------------- */

static bool swa_is_part(const char *name)
{
   return string_is_equal_noncase(name, "exefs")
       || string_is_equal_noncase(name, "romfs")
       || string_is_equal_noncase(name, "cheats");
}

/* Whether dir holds exefs, romfs or cheats. */
static bool swa_has_parts(const char *dir)
{
   struct string_list *list = dir_list_new(dir, NULL, true, true, false,
         false);
   size_t i;
   bool yes = false;
   for (i = 0; list && i < list->size && !yes; i++)
      yes = list->elems[i].attr.i == RARCH_DIRECTORY
         && swa_is_part(path_basename(list->elems[i].data));
   if (list)
      string_list_free(list);
   return yes;
}

/* Every mod folder at or under dir. */
static void swa_find_mods(const char *dir, struct string_list *out, int depth)
{
   struct string_list *list;
   union string_list_elem_attr attr;
   size_t i;

   attr.i = 0;
   if (swa_has_parts(dir))
   {
      string_list_append(out, dir, attr);
      return;
   }
   if (depth > 6 || !(list = dir_list_new(dir, NULL, true, true, false,
               false)))
      return;
   for (i = 0; i < list->size; i++)
      if (list->elems[i].attr.i == RARCH_DIRECTORY)
         swa_find_mods(list->elems[i].data, out, depth + 1);
   string_list_free(list);
}

#ifdef _WIN32
static bool swa_move(const char *src, const char *dst)
{
   wchar_t *ws = utf8_to_utf16_string_alloc(src);
   wchar_t *wd = utf8_to_utf16_string_alloc(dst);
   bool ok     = ws && wd && MoveFileExW(ws, wd, MOVEFILE_COPY_ALLOWED);
   free(ws);
   free(wd);
   return ok;
}
#endif

static bool swa_copy_file(const char *src, const char *dst)
{
   uint8_t chunk[65536];
   int64_t n;
   bool ok    = true;
   RFILE *in  = filestream_open(src, RETRO_VFS_FILE_ACCESS_READ,
         RETRO_VFS_FILE_ACCESS_HINT_NONE);
   RFILE *out = in ? filestream_open(dst, RETRO_VFS_FILE_ACCESS_WRITE,
         RETRO_VFS_FILE_ACCESS_HINT_NONE) : NULL;

   if (!in || !out)
      ok = false;
   while (ok && (n = filestream_read(in, chunk, sizeof(chunk))) > 0)
      ok = filestream_write(out, chunk, n) == n;
   if (in)
      filestream_close(in);
   if (out)
      filestream_close(out);
   return ok;
}

static bool swa_copy_tree(const char *src, const char *dst)
{
   struct string_list *list = dir_list_new(src, NULL, true, true, false,
         false);
   size_t i;
   bool ok = path_mkdir(dst);

   for (i = 0; ok && list && i < list->size; i++)
   {
      char to[PATH_MAX_LENGTH];
      const char *from = list->elems[i].data;
      fill_pathname_join_special(to, dst, path_basename(from), sizeof(to));
      if (list->elems[i].attr.i == RARCH_DIRECTORY)
         ok = swa_copy_tree(from, to);
      else if (list->elems[i].attr.i == RARCH_PLAIN_FILE)
         ok = swa_copy_file(from, to);
   }
   if (list)
      string_list_free(list);
   return ok;
}

static void swa_install_mods(swa_job_t *job)
{
   struct string_list *mods = string_list_new();
   char dir[PATH_MAX_LENGTH];
   size_t i;

   if (!mods)
      return;
   swa_find_mods(job->src, mods, 0);
   if (!mods->size)
   {
      strlcpy(job->error, "No mod in that (no exefs, romfs or cheats folder)",
            sizeof(job->error));
      string_list_free(mods);
      return;
   }

   swa_mod_dir(job->user, job->tid, dir, sizeof(dir));
   path_mkdir(dir);
   for (i = 0; i < mods->size; i++)
   {
      const char *src = mods->elems[i].data;
      char name[256], dst[PATH_MAX_LENGTH];
      bool ok;

      /* Named by its folder, unless that is a title ID (Atmosphere's
       * contents/<id>) or the extraction folder: then by what it came
       * from. */
      strlcpy(name, path_basename(src), sizeof(name));
      if (swa_is_tid(name))
      {
         uint64_t t = 0;
         int k;
         for (k = 0; k < 16; k++)
            t = t << 4 | (uint64_t)swa_hex(name[k]);
         if (swa_base_of(t) != job->tid)
         {
            strlcpy(job->error, "That mod is for another game",
                  sizeof(job->error));
            continue;
         }
      }
      if (     swa_is_tid(name) || string_is_equal(name, SWA_TMP)
            || string_is_empty(name))
         strlcpy(name, job->label, sizeof(name));

      fill_pathname_join_special(dst, dir, name, sizeof(dst));
      grid_switch_rmtree(dst);
#ifdef _WIN32
      /* Out of the extraction folder (on the same drive): just moved. */
      ok = job->cleanup ? swa_move(src, dst) : swa_copy_tree(src, dst);
#else
      ok = swa_copy_tree(src, dst);
#endif
      if (!ok)
      {
         grid_switch_rmtree(dst);
         strlcpy(job->error, "Couldn't copy the mod", sizeof(job->error));
         continue;
      }
      job->ok = true;
   }
   string_list_free(mods);
   if (job->ok)
      job->error[0] = '\0';
}

/* ---- Turning mods off ------------------------------------------------- */

typedef struct
{
   uint64_t tid;
   unsigned idx;              /* its number in the config */
   bool has_tid;
   struct string_list *names;
} swa_disabled_t;

/* Eden's [DisabledAddOns] in one config text: "N\title_id=<decimal>",
 * "N\disabled\M\d=<name>" (1-based, a QSettings array). */
static size_t swa_disabled_parse(const char *text, swa_disabled_t *out,
      size_t max)
{
   const char *sec = text ? strstr(text, "[DisabledAddOns]") : NULL;
   const char *p;
   size_t n = 0, i;

   if (!sec)
      return 0;
   for (p = strchr(sec, '\n'); p && p[1] && p[1] != '['; p = strchr(p + 1, '\n'))
   {
      const char *l = p + 1;
      char *end;
      unsigned long idx = strtoul(l, &end, 10);
      size_t k;

      if (!idx || *end != '\\')
         continue;
      end++;
      /* Entry idx (gaps allowed). */
      for (k = 0; k < n; k++)
         if (out[k].idx == idx)
            break;
      if (k == n)
      {
         if (n == max)
            continue;
         out[n].tid     = 0;
         out[n].idx     = (unsigned)idx;
         out[n].has_tid = false;
         out[n].names   = string_list_new();
         n++;
      }
      if (!strncmp(end, "title_id=", 9))
      {
         out[k].tid     = (uint64_t)strtoull(end + 9, NULL, 10);
         out[k].has_tid = true;
      }
      else if (!strncmp(end, "disabled\\", 9))
      {
         char *e2;
         strtoul(end + 9, &e2, 10);
         if (!strncmp(e2, "\\d=", 3))
         {
            char name[256];
            const char *v  = e2 + 3;
            const char *nl = strpbrk(v, "\r\n");
            size_t len     = nl ? (size_t)(nl - v) : strlen(v);
            union string_list_elem_attr attr;
            attr.i = 0;
            if (len >= sizeof(name))
               len = sizeof(name) - 1;
            memcpy(name, v, len);
            name[len] = '\0';
            if (*name && out[k].names)
               string_list_append(out[k].names, name, attr);
         }
      }
   }
   /* Entries without a title_id line: dropped. */
   for (i = 0; i < n; i++)
      if (!out[i].has_tid)
      {
         string_list_free(out[i].names);
         out[i--] = out[--n];
      }
   return n;
}

/* The config text with [DisabledAddOns] rewritten from list. */
static char *swa_disabled_write(const char *text, const swa_disabled_t *list,
      size_t n)
{
   size_t cap = (text ? strlen(text) : 0) + 64, o = 0, i, j;
   const char *sec = text ? strstr(text, "[DisabledAddOns]") : NULL;
   const char *after = NULL;
   char *out;

   for (i = 0; i < n; i++)
   {
      cap += 96;
      for (j = 0; list[i].names && j < list[i].names->size; j++)
         cap += 64 + strlen(list[i].names->elems[j].data);
   }
   if (!(out = (char*)malloc(cap)))
      return NULL;

   if (sec)
   {
      /* Up to the section, then on from the next one. */
      const char *p = sec;
      while ((p = strchr(p, '\n')) && p[1] && p[1] != '[')
         p++;
      after = p ? p + 1 : NULL;
      memcpy(out, text, (size_t)(sec - text));
      o = (size_t)(sec - text);
   }
   else if (text)
   {
      size_t tl = strlen(text);
      memcpy(out, text, tl);
      o = tl;
      if (o && out[o - 1] != '\n')
         out[o++] = '\n';
      out[o++] = '\n';
   }

   o += (size_t)sprintf(out + o, "[DisabledAddOns]\nsize=%u\n", (unsigned)n);
   for (i = 0; i < n; i++)
   {
      size_t m = list[i].names ? list[i].names->size : 0;
      o += (size_t)sprintf(out + o, "%u\\title_id\\default=false\n"
            "%u\\title_id=%llu\n", (unsigned)(i + 1), (unsigned)(i + 1),
            (unsigned long long)list[i].tid);
      for (j = 0; j < m; j++)
         o += (size_t)sprintf(out + o, "%u\\disabled\\%u\\d\\default=false\n"
               "%u\\disabled\\%u\\d=%s\n", (unsigned)(i + 1),
               (unsigned)(j + 1), (unsigned)(i + 1), (unsigned)(j + 1),
               list[i].names->elems[j].data);
      o += (size_t)sprintf(out + o, "%u\\disabled\\size=%u\n",
            (unsigned)(i + 1), (unsigned)m);
   }
   out[o++] = '\n';
   if (after)
   {
      size_t al = strlen(after);
      if (o + al + 1 > cap)
      {
         char *grown = (char*)realloc(out, o + al + 1);
         if (!grown)
         {
            free(out);
            return NULL;
         }
         out = grown;
      }
      memcpy(out + o, after, al);
      o += al;
   }
   out[o] = '\0';
   return out;
}

static void swa_config_path(const char *user, bool qt, char *s, size_t len)
{
   fill_pathname_join_special(s, user, qt ? "config/qt-config.ini"
         : "config/sdl2-config.ini", len);
}

/* Whether mod name is turned off for tid (in eden.exe's config). */
static bool swa_mod_disabled(const char *user, uint64_t tid, const char *name)
{
   char path[PATH_MAX_LENGTH];
   swa_disabled_t list[64];
   void *buf = NULL;
   int64_t len = 0;
   size_t n, i, j;
   bool off = false;

   swa_config_path(user, true, path, sizeof(path));
   if (!filestream_read_file(path, &buf, &len) || !buf)
      return false;
   n = swa_disabled_parse((const char*)buf, list, 64);
   for (i = 0; i < n; i++)
   {
      for (j = 0; list[i].tid == tid && list[i].names
            && j < list[i].names->size; j++)
         if (string_is_equal(list[i].names->elems[j].data, name))
            off = true;
      string_list_free(list[i].names);
   }
   free(buf);
   return off;
}

/* Turns mod name off (or back on) for tid, in both of Eden's configs. */
static bool swa_mod_set_disabled(const char *user, uint64_t tid,
      const char *name, bool off)
{
   int qt;
   bool any = false;

   for (qt = 1; qt >= 0; qt--)
   {
      char path[PATH_MAX_LENGTH];
      swa_disabled_t list[64];
      void *buf = NULL;
      int64_t len = 0;
      size_t n, i, j;
      char *text;

      swa_config_path(user, qt != 0, path, sizeof(path));
      if (!filestream_read_file(path, &buf, &len) || !buf)
      {
         if (!qt)
            continue;  /* sdl2-config.ini: made by eden-cli when it runs */
         buf = calloc(1, 1);
         if (!buf)
            continue;
      }
      n = swa_disabled_parse((const char*)buf, list, 63);

      for (i = 0; i < n && list[i].tid != tid; i++);
      if (i == n && off)
      {
         list[n].tid     = tid;
         list[n].has_tid = true;
         list[n].names   = string_list_new();
         n++;
      }
      if (i < n && list[i].names)
      {
         for (j = 0; j < list[i].names->size; j++)
            if (string_is_equal(list[i].names->elems[j].data, name))
               break;
         if (off && j == list[i].names->size)
         {
            union string_list_elem_attr attr;
            attr.i = 0;
            string_list_append(list[i].names, name, attr);
         }
         else if (!off && j < list[i].names->size)
         {
            struct string_list *l = list[i].names;
            free(l->elems[j].data);
            memmove(&l->elems[j], &l->elems[j + 1],
                  (l->size - j - 1) * sizeof(l->elems[0]));
            l->size--;
         }
      }

      if ((text = swa_disabled_write((const char*)buf, list, n)))
      {
         char dir[PATH_MAX_LENGTH];
         fill_pathname_basedir(dir, path, sizeof(dir));
         path_mkdir(dir);
         any = filestream_write_file(path, text, (int64_t)strlen(text)) || any;
         free(text);
      }
      for (i = 0; i < n; i++)
         string_list_free(list[i].names);
      free(buf);
   }
   return any;
}

/* ---- The list --------------------------------------------------------- */

static void swa_refresh(void)
{
   char user[PATH_MAX_LENGTH];

   swa_st.count   = 0;
   swa_st.changed = true;
   if (!swa_st.tid || !swa_user(user, sizeof(user)))
      return;

   if (swa_st.kind == GRID_ADDON_MODS)
   {
      char dir[PATH_MAX_LENGTH];
      struct string_list *list;
      size_t i;

      swa_mod_dir(user, swa_st.tid, dir, sizeof(dir));
      if (!(list = path_is_directory(dir)
               ? dir_list_new(dir, NULL, true, true, false, false) : NULL))
         return;
      dir_list_sort(list, true);
      for (i = 0; i < list->size && swa_st.count < SWA_MAX; i++)
      {
         grid_addon_t *a;
         if (list->elems[i].attr.i != RARCH_DIRECTORY)
            continue;
         a = &swa_st.items[swa_st.count++];
         strlcpy(a->name, path_basename(list->elems[i].data), sizeof(a->name));
         a->on  = !swa_mod_disabled(user, swa_st.tid, a->name);
         a->dlc = false;
      }
      string_list_free(list);
   }
   else
   {
      static char rel[SWA_MAX][64];
      static uint64_t tids[SWA_MAX];
      char *text = swa_manifest_read(user);
      size_t i, n = swa_find_metas(user, swa_st.tid, false, rel, tids,
            SWA_MAX);

      for (i = 0; i < n; i++)
      {
         grid_addon_t *a = &swa_st.items[swa_st.count];
         a->dlc = (tids[i] & 0xFFF) != 0x800;
         a->on  = true;
         if (!swa_manifest_find(text, tids[i], a->name, sizeof(a->name),
                  NULL, 0))
            snprintf(a->name, sizeof(a->name), "%s %016llX",
                  a->dlc ? "DLC" : "Update", (unsigned long long)tids[i]);
         strlcpy(swa_st.files[swa_st.count], rel[i], sizeof(swa_st.files[0]));
         swa_st.count++;
      }
      free(text);
   }
}

void grid_addons_open(const char *rom, enum grid_addon_kind kind)
{
   char user[PATH_MAX_LENGTH];

   swa_st.kind     = kind;
   swa_st.error[0] = '\0';
   /* The same game again: its ID is known. */
   if (!string_is_equal(swa_st.rom, rom) || !swa_st.tid)
   {
      strlcpy(swa_st.rom, rom, sizeof(swa_st.rom));
      swa_st.tid        = 0;
      swa_st.no_game[0] = '\0';
      if (!swa_user(user, sizeof(user)) || !grid_switch_available())
         strlcpy(swa_st.no_game, "Install Eden first (Downloads)",
               sizeof(swa_st.no_game));
      else
         swa_game_tid(rom, user, &swa_st.tid, swa_st.no_game,
               sizeof(swa_st.no_game));
   }
   swa_refresh();
}

void grid_addons_close(void)
{
   swa_st.count = 0;
}

enum grid_addons_state grid_addons_state(char *detail, size_t len)
{
   if (!swa_st.tid)
   {
      strlcpy(detail, swa_st.no_game, len);
      return GRID_ADDONS_NO_GAME;
   }
   if (swa_st.job || swa_st.extracting)
   {
      if (swa_st.job && swa_st.job->progress)
         snprintf(detail, len, "Installing... %u%%", swa_st.job->progress);
      else
         strlcpy(detail, "Installing...", len);
      return GRID_ADDONS_WORKING;
   }
   if (!string_is_empty(swa_st.error))
   {
      strlcpy(detail, swa_st.error, len);
      return GRID_ADDONS_FAILED;
   }
   detail[0] = '\0';
   return GRID_ADDONS_READY;
}

