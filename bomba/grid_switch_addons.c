static void swa_thread(void *data)
{
   swa_job_t *job = (swa_job_t*)data;
   if (job->kind == GRID_ADDON_MODS)
      swa_install_mods(job);
   else
      swa_install_nsp(job);
   if (job->cleanup)
      grid_switch_rmtree(job->src);
   job->done = true;
}

static void swa_start(void)
{
#ifdef HAVE_THREADS
   if ((swa_st.job->thread = sthread_create(swa_thread, swa_st.job)))
      return;
#endif
   strlcpy(swa_st.error, "Couldn't install", sizeof(swa_st.error));
   if (swa_st.job->cleanup)
      grid_switch_rmtree(swa_st.job->src);
   free(swa_st.job);
   swa_st.job = NULL;
}

#ifdef SWA_HAVE_ZIP
static void swa_extract_cb(retro_task_t *task, void *task_data,
      void *user_data, const char *error)
{
   decompress_task_data_t *dec = (decompress_task_data_t*)task_data;

   if (dec)
   {
      free(dec->source_file);
      free(dec);
   }
   swa_st.extracting = false;
   swa_st.changed    = true;
   if (!swa_st.job)
      return;
   if (!string_is_empty(error))
   {
      grid_switch_rmtree(swa_st.job->src);
      strlcpy(swa_st.error, "Couldn't open that zip", sizeof(swa_st.error));
      free(swa_st.job);
      swa_st.job = NULL;
      return;
   }
   swa_start();
}
#endif

/* A file picked inside a mod's folder: the mod's folder (the one holding
 * exefs / romfs / cheats, or the parent of one of those it is in). */
static bool swa_mod_root(const char *file, char *s, size_t len)
{
   char cur[PATH_MAX_LENGTH];
   int depth;

   fill_pathname_basedir(cur, file, sizeof(cur));
   {
      size_t l = strlen(cur);
      while (l > 3 && (cur[l - 1] == '/' || cur[l - 1] == '\\'))
         cur[--l] = '\0';
   }
   for (depth = 0; depth < 8 && *cur; depth++)
   {
      char parent[PATH_MAX_LENGTH];
      if (swa_has_parts(cur))
      {
         strlcpy(s, cur, len);
         return true;
      }
      fill_pathname_parent_dir(parent, cur, sizeof(parent));
      {
         size_t l = strlen(parent);
         while (l > 3 && (parent[l - 1] == '/' || parent[l - 1] == '\\'))
            parent[--l] = '\0';
      }
      if (swa_is_part(path_basename(cur)))
      {
         strlcpy(s, parent, len);
         return true;
      }
      if (string_is_equal(parent, cur))
         break;
      strlcpy(cur, parent, sizeof(cur));
   }
   return false;
}

static bool swa_add(const char *path)
{
   char user[PATH_MAX_LENGTH];
   const char *ext = path_get_extension(path);

   if (swa_st.job || swa_st.extracting || !swa_st.tid
         || !swa_user(user, sizeof(user)))
      return false;
   if (!(swa_st.job = (swa_job_t*)calloc(1, sizeof(*swa_st.job))))
      return false;
   swa_st.job->kind = swa_st.kind;
   swa_st.job->tid  = swa_st.tid;
   strlcpy(swa_st.job->user, user, sizeof(swa_st.job->user));
   /* Shown as the file's name without its extension; a mod is named so
    * when the folder in its zip doesn't say. */
   fill_pathname_base(swa_st.job->label, path, sizeof(swa_st.job->label));
   path_remove_extension(swa_st.job->label);
   swa_st.error[0] = '\0';
   swa_st.changed  = true;

   if (swa_st.kind == GRID_ADDON_UPDATES)
   {
      strlcpy(swa_st.job->src, path, sizeof(swa_st.job->src));
      swa_start();
      return swa_st.job != NULL;
   }

#ifdef SWA_HAVE_ZIP
   if (string_is_equal_noncase(ext, "zip"))
   {
      char eden[PATH_MAX_LENGTH];
      fill_pathname_basedir(eden, user, sizeof(eden));
      fill_pathname_join_special(swa_st.job->src, eden, SWA_TMP,
            sizeof(swa_st.job->src));
      swa_st.job->cleanup = true;
      grid_switch_rmtree(swa_st.job->src);
      path_mkdir(swa_st.job->src);
      swa_st.extracting = true;
      if (task_push_decompress(path, swa_st.job->src, NULL, NULL, NULL,
               swa_extract_cb, NULL, NULL, true))
         return true;
      swa_st.extracting = false;
      grid_switch_rmtree(swa_st.job->src);
      strlcpy(swa_st.error, "Couldn't open that zip", sizeof(swa_st.error));
      free(swa_st.job);
      swa_st.job = NULL;
      return false;
   }
#else
   (void)ext;
#endif

   if (!swa_mod_root(path, swa_st.job->src, sizeof(swa_st.job->src)))
   {
      strlcpy(swa_st.error, "No mod there (no exefs, romfs or cheats folder)",
            sizeof(swa_st.error));
      free(swa_st.job);
      swa_st.job = NULL;
      return false;
   }
   fill_pathname_base(swa_st.job->label, swa_st.job->src,
         sizeof(swa_st.job->label));
   swa_start();
   return swa_st.job != NULL;
}

bool grid_addons_browse(const char *running_core)
{
#ifdef _WIN32
   char *path;
   bool ok;

   if (swa_st.job || swa_st.extracting || !swa_st.tid
         || swa_eden_running(running_core))
      return false;
   if (swa_st.kind == GRID_ADDON_MODS)
      path = grid_switch_open_dialog(L"Choose a mod (a .zip, or any file "
            L"in the mod's folder)",
            L"Mods (*.zip, or a file in the mod's folder)\0*.*\0"
            L"Zip files (*.zip)\0*.zip\0");
   else
      path = grid_switch_open_dialog(L"Choose an update or DLC (.nsp)",
            L"Switch updates and DLC (*.nsp)\0*.nsp\0All files\0*.*\0");
   if (!path)
      return false;
   ok = swa_add(path);
   free(path);
   return ok;
#else
   return false;
#endif
}

bool grid_addons_toggle(size_t i, const char *running_core)
{
   char user[PATH_MAX_LENGTH];
   grid_addon_t *a;

   if (     swa_st.kind != GRID_ADDON_MODS || i >= swa_st.count
         || swa_st.job || swa_eden_running(running_core)
         || !swa_user(user, sizeof(user)))
      return false;
   a = &swa_st.items[i];
   if (!swa_mod_set_disabled(user, swa_st.tid, a->name, a->on))
   {
      strlcpy(swa_st.error, "Couldn't change Eden's settings",
            sizeof(swa_st.error));
      swa_st.changed = true;
      return false;
   }
   a->on          = !a->on;
   swa_st.changed = true;
   return true;
}

bool grid_addons_remove(size_t i, const char *running_core)
{
   char user[PATH_MAX_LENGTH];
   bool ok;

   if (     i >= swa_st.count || swa_st.job || swa_st.extracting
         || swa_eden_running(running_core) || !swa_user(user, sizeof(user)))
      return false;

   if (swa_st.kind == GRID_ADDON_MODS)
   {
      char dir[PATH_MAX_LENGTH], mod[PATH_MAX_LENGTH];
      swa_mod_dir(user, swa_st.tid, dir, sizeof(dir));
      fill_pathname_join_special(mod, dir, swa_st.items[i].name, sizeof(mod));
      ok = grid_switch_rmtree(mod);
      if (ok && !swa_st.items[i].on)
         swa_mod_set_disabled(user, swa_st.tid, swa_st.items[i].name, false);
   }
   else
   {
      /* Its title ID: from the meta NCA itself. */
      char reg[PATH_MAX_LENGTH], path[PATH_MAX_LENGTH];
      uint8_t key[32];
      swa_nca_t nca;
      swa_registered(user, reg, sizeof(reg));
      fill_pathname_join_special(path, reg, swa_st.files[i], sizeof(path));
      ok = swa_header_key(user, key) && swa_nca_file_info(path, key, &nca)
        && swa_remove_title(user, nca.tid, swa_st.files[i]);
   }

   if (ok)
   {
      swa_st.error[0] = '\0';
      swa_toast(swa_st.kind == GRID_ADDON_MODS ? "Mod removed" : "Removed");
   }
   else
      strlcpy(swa_st.error, "Couldn't remove it", sizeof(swa_st.error));
   swa_refresh();
   return ok;
}

bool grid_addons_poll(void)
{
   bool changed;

   if (swa_st.job && !swa_st.extracting && swa_st.job->done)
   {
#ifdef HAVE_THREADS
      sthread_join(swa_st.job->thread);
#endif
      if (swa_st.job->ok)
      {
         swa_st.error[0] = '\0';
         swa_toast(swa_st.job->kind == GRID_ADDON_MODS ? "Mod added"
               : "Installed");
      }
      else
         strlcpy(swa_st.error, string_is_empty(swa_st.job->error)
               ? "Couldn't install" : swa_st.job->error,
               sizeof(swa_st.error));
      /* Shown only while its game's list is: the next open re-reads. */
      if (swa_st.job->tid == swa_st.tid && swa_st.job->kind == swa_st.kind)
         swa_refresh();
      free(swa_st.job);
      swa_st.job = NULL;
      swa_st.changed = true;
   }
   else if (swa_st.job && swa_st.job->progress)
      swa_st.changed = true;  /* the percentage moves */

   changed        = swa_st.changed;
   swa_st.changed = false;
   return changed;
}
