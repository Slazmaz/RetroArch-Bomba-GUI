/* Bomba: a Switch game's mods, updates and DLC, for Eden.
 *
 * Kept where both of Eden's programs read them, in its portable user
 * folder (<system>/Eden/user):
 *    load/<title ID>/<mod name>/exefs|romfs|cheats
 *    nand/user/Contents/registered/<NCA id>.nca (and <id>.cnmt.nca)
 * eden-cli.exe (multiplayer) reads no folder of loose update files, which
 * is why updates are installed into the NAND rather than kept beside the
 * games.
 *
 * The game's title ID comes from its file: an .nsp is a PFS0 of NCAs, an
 * .xci a card image whose "secure" HFS0 partition holds them. An NCA's
 * header (title ID at 0x210, content type at 0x205) is AES-XTS encrypted
 * with prod.keys' header_key, in 0x200-byte sectors whose tweak is the
 * sector number, big-endian.
 *
 * Installing an update or DLC copies its .nsp's NCAs (named by their ids,
 * which is how Eden finds them) and adds the title keys of its common
 * tickets to keys/title.keys_autogenerated, as Eden does when it installs
 * one itself. <user>/bomba-addons.txt lists what was installed from where,
 * so removing takes all of it: "<title ID>\t<label>\t<file>|<file>...".
 * An entry not in it (Eden installed it) is removed by its meta NCA, which
 * is what makes Eden see it.
 *
 * Mods come from a .zip or a folder, laid out however they were shared
 * (SMOO/exefs, atmosphere/contents/<id>/romfs, a bare exefs...): each
 * folder holding exefs, romfs or cheats is one mod. Turned off, a mod is
 * in Eden's [DisabledAddOns] (both qt-config.ini and sdl2-config.ini).
 * Nothing changes while Eden runs: it would write its config over ours.
 */

